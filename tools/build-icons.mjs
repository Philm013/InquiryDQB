const out = {};
const missing = [];
for (const [name, file] of Object.entries(ICONS)) {
  const p = join(dir, file + '.svg');
  if (!existsSync(p)) { missing.push(`${name} -> ${file}`); continue; }
  const svg = readFileSync(p, 'utf8');
  const inner = svg.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
    .replace(/\s+/g, ' ').replace(/> </g, '><').replace(/ \/>/g, '/>').trim();
  out[name] = inner;
}
if (missing.length) console.warn('Missing icons:\n  ' + missing.join('\n  '));

const js = `/* AUTO-GENERATED by tools/build-icons.mjs from Lucide (ISC licence, https://lucide.dev). Do not edit by hand. */
(function () {
  var I = ${JSON.stringify(out)};
  window.DQB_ICONS = I;
  /** Returns an inline <svg> string (stroke icons that inherit currentColor). */
  window.icon = function (name, cls) {
    return '<svg class="i' + (cls ? ' ' + cls : '') + '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' + (I[name] || '') + '</svg>';
  };
  /** Replaces <i data-i="name"></i> placeholders under root with inline SVG icons. */
  window.hydrateIcons = function (root) {
    (root || document).querySelectorAll('i[data-i]').forEach(function (el) {
      el.outerHTML = window.icon(el.getAttribute('data-i'), el.getAttribute('class') || '');
    });
  };
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', function () { window.hydrateIcons(); });
  else window.hydrateIcons();
})();
`;
writeFileSync(join(here, '..', 'shared', 'icons.js'), js);
